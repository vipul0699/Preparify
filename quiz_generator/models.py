import uuid
from django.conf import settings
from django.db import models

class TopicMaterial(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    topic = models.CharField(max_length=255)
    content = models.TextField()
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.topic} Material"

class QuizSession(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True,
        on_delete=models.CASCADE, related_name='quiz_sessions'
    )
    topic = models.CharField(max_length=255)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Quiz on {self.topic} ({self.created_at})"

class Question(models.Model):
    DIFFICULTY_CHOICES = [
        ('Easy', 'Easy'),
        ('Medium', 'Medium'),
        ('Hard', 'Hard'),
    ]
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    quiz_session = models.ForeignKey(QuizSession, related_name='questions', on_delete=models.CASCADE)
    text = models.TextField()
    difficulty = models.CharField(max_length=10, choices=DIFFICULTY_CHOICES)
    generated_answer = models.TextField(help_text="Reference answer generated by LLM")
    explanation = models.TextField(null=True, blank=True, help_text="AI explanation for the correct answer")

    def __str__(self):
        return f"[{self.difficulty}] {self.text[:50]}..."

class UserResponse(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    question = models.ForeignKey(Question, related_name='responses', on_delete=models.CASCADE)
    user_answer = models.TextField()
    score = models.IntegerField(default=0, help_text="Score from 0 to 100")
    feedback = models.TextField()
    is_correct = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Response to {self.question.id} - Score: {self.score}"
